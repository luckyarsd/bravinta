const inside = (x, y) => {
  let c = false;
  for (let i = 0, j = OUT.length - 1; i < OUT.length; j = i++) {
    const [xi, yi] = OUT[i],
      [xj, yj] = OUT[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};
